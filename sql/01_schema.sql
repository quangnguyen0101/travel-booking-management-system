USE [BTL2_Booking_Nhom5];
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF DB_NAME() <> N'BTL2_Booking_Nhom5'
    THROW 51000, N'Dang chon sai database. Dung script va kiem tra lenh USE.', 1;
IF EXISTS (SELECT 1 FROM sys.tables WHERE is_ms_shipped = 0)
    THROW 51001, N'Database da co bang. Script dung lai de tranh ghi de. Khong tu dong xoa du lieu.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    -- 1. Tài khoản người dùng. Tên USER đặt trong [] để tránh trùng từ khóa.
    CREATE TABLE dbo.[USER] (
        USER_ID INT IDENTITY(1,1) NOT NULL,
        EMAIL NVARCHAR(254) NOT NULL,
        [PASSWORD] VARCHAR(255) NOT NULL, -- Lưu mật khẩu đã băm.
        FULL_NAME NVARCHAR(150) NOT NULL,
        PHONE_NUMBER VARCHAR(20) NULL,
        PROFILE_IMAGE NVARCHAR(2048) NULL,
        CREATED_DATE DATETIME2(0) NOT NULL CONSTRAINT DF_USER_CREATED DEFAULT (SYSDATETIME()),
        STREET_ADDRESS NVARCHAR(200) NULL,
        WARD NVARCHAR(100) NULL,
        DISTRICT NVARCHAR(100) NULL,
        CITY NVARCHAR(100) NULL,
        CONSTRAINT PK_USER PRIMARY KEY (USER_ID),
        CONSTRAINT UQ_USER_EMAIL UNIQUE (EMAIL),
        CONSTRAINT CK_USER_EMAIL_NOT_EMPTY CHECK (LEN(LTRIM(RTRIM(EMAIL))) > 0),
        CONSTRAINT CK_USER_NAME_NOT_EMPTY CHECK (LEN(LTRIM(RTRIM(FULL_NAME))) > 0)
    );

    -- 2. Mỗi người dùng có tối đa một người giới thiệu.
    CREATE TABLE dbo.REFER (
        REFERRED_USER_ID INT NOT NULL,
        REFERRER_ID INT NOT NULL,
        CONSTRAINT PK_REFER PRIMARY KEY (REFERRED_USER_ID),
        CONSTRAINT FK_REFER_REFERRED FOREIGN KEY (REFERRED_USER_ID) REFERENCES dbo.[USER](USER_ID),
        CONSTRAINT FK_REFER_REFERRER FOREIGN KEY (REFERRER_ID) REFERENCES dbo.[USER](USER_ID),
        CONSTRAINT CK_REFER_NOT_SELF CHECK (REFERRED_USER_ID <> REFERRER_ID)
    );

    -- 3-5. Khách, chủ cơ sở và quản trị viên dùng lại USER_ID của bảng USER.
    CREATE TABLE dbo.GUEST (
        USER_ID INT NOT NULL,
        BIRTH_DATE DATE NULL,
        GENDER VARCHAR(10) NULL,
        CONSTRAINT PK_GUEST PRIMARY KEY (USER_ID),
        CONSTRAINT FK_GUEST_USER FOREIGN KEY (USER_ID) REFERENCES dbo.[USER](USER_ID),
        CONSTRAINT CK_GUEST_GENDER CHECK (GENDER IN ('MALE','FEMALE','OTHER'))
    );

    CREATE TABLE dbo.HOST (
        USER_ID INT NOT NULL,
        TAX_CODE VARCHAR(30) NOT NULL,
        BUSINESS_NAME NVARCHAR(200) NOT NULL,
        BANK_ACCOUNT VARCHAR(50) NOT NULL,
        CONSTRAINT PK_HOST PRIMARY KEY (USER_ID),
        CONSTRAINT FK_HOST_USER FOREIGN KEY (USER_ID) REFERENCES dbo.[USER](USER_ID),
        CONSTRAINT UQ_HOST_TAX_CODE UNIQUE (TAX_CODE)
    );

    CREATE TABLE dbo.[ADMIN] (
        USER_ID INT NOT NULL,
        ADMIN_ROLE NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_ADMIN PRIMARY KEY (USER_ID),
        CONSTRAINT FK_ADMIN_USER FOREIGN KEY (USER_ID) REFERENCES dbo.[USER](USER_ID)
    );

    -- 6-7. Ví khách hàng và các mục lịch sử giao dịch.
    CREATE TABLE dbo.WALLET (
        USER_ID INT NOT NULL,
        BALANCE DECIMAL(18,2) NOT NULL CONSTRAINT DF_WALLET_BALANCE DEFAULT (0),
        LOYALTY_POINTS INT NOT NULL CONSTRAINT DF_WALLET_POINTS DEFAULT (0),
        CONSTRAINT PK_WALLET PRIMARY KEY (USER_ID),
        CONSTRAINT FK_WALLET_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID),
        CONSTRAINT CK_WALLET_BALANCE CHECK (BALANCE >= 0),
        CONSTRAINT CK_WALLET_POINTS CHECK (LOYALTY_POINTS >= 0)
    );

    CREATE TABLE dbo.WALLET_TRANSACTION (
        USER_ID INT NOT NULL,
        TRANSACTION_HISTORY NVARCHAR(300) NOT NULL,
        CONSTRAINT PK_WALLET_TRANSACTION PRIMARY KEY (USER_ID, TRANSACTION_HISTORY),
        CONSTRAINT FK_WALLET_TRANSACTION_WALLET FOREIGN KEY (USER_ID) REFERENCES dbo.WALLET(USER_ID)
    );

    -- 8. Người đi cùng được đánh số riêng theo từng khách.
    CREATE TABLE dbo.COMPANION (
        USER_ID INT NOT NULL,
        COMPANION_NO INT NOT NULL,
        FULL_NAME NVARCHAR(150) NOT NULL,
        BIRTH_DATE DATE NULL,
        PHONE_NUMBER VARCHAR(20) NULL,
        CONSTRAINT PK_COMPANION PRIMARY KEY (USER_ID, COMPANION_NO),
        CONSTRAINT FK_COMPANION_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID),
        CONSTRAINT CK_COMPANION_NO CHECK (COMPANION_NO > 0)
    );

    -- 9. Lưu số thẻ dạng chuỗi để giữ số 0 ở đầu. Dữ liệu mẫu dùng thẻ giả lập.
    CREATE TABLE dbo.PAYMENT_CARD (
        CARD_NUMBER VARCHAR(19) NOT NULL,
        CARDHOLDER_NAME NVARCHAR(150) NOT NULL,
        EXPIRY_DATE DATE NOT NULL,
        CARD_TYPE VARCHAR(20) NOT NULL,
        USER_ID INT NOT NULL,
        CONSTRAINT PK_PAYMENT_CARD PRIMARY KEY (CARD_NUMBER),
        CONSTRAINT FK_PAYMENT_CARD_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID)
    );

    -- 10. Voucher hiện lưu mức giảm bằng số tiền; lược đồ chưa tách loại giảm theo %.
    CREATE TABLE dbo.VOUCHER (
        VOUCHER_CODE VARCHAR(50) NOT NULL,
        DISCOUNT_VALUE DECIMAL(18,2) NOT NULL,
        APPLICABLE_CONDITIONS NVARCHAR(1000) NULL,
        EXPIRY_DATE DATE NOT NULL,
        [STATUS] VARCHAR(10) NOT NULL CONSTRAINT DF_VOUCHER_STATUS DEFAULT ('ACTIVE'),
        USER_ID INT NOT NULL,
        CONSTRAINT PK_VOUCHER PRIMARY KEY (VOUCHER_CODE),
        CONSTRAINT FK_VOUCHER_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID),
        CONSTRAINT CK_VOUCHER_DISCOUNT CHECK (DISCOUNT_VALUE > 0),
        CONSTRAINT CK_VOUCHER_STATUS CHECK ([STATUS] IN ('ACTIVE','EXPIRED','USED'))
    );

    -- 11. Tạo cơ sở lưu trú trước vì WISHLIST cần tham chiếu đến bảng này.
    CREATE TABLE dbo.ACCOMMODATION (
        ACCOMMODATION_ID INT IDENTITY(1,1) NOT NULL,
        [NAME] NVARCHAR(200) NOT NULL,
        [DESCRIPTION] NVARCHAR(MAX) NULL,
        STAR_RATING TINYINT NOT NULL,
        CHECK_IN_TIME TIME(0) NOT NULL CONSTRAINT DF_ACCOM_CHECKIN DEFAULT ('14:00:00'),
        CHECK_OUT_TIME TIME(0) NOT NULL CONSTRAINT DF_ACCOM_CHECKOUT DEFAULT ('12:00:00'),
        CANCELLATION_POLICY NVARCHAR(1000) NULL,
        PET_POLICY NVARCHAR(500) NULL,
        CHILD_POLICY NVARCHAR(500) NULL,
        CONTACT_EMAIL NVARCHAR(254) NULL,
        PHONE_NUMBER VARCHAR(20) NULL,
        STREET_ADDRESS NVARCHAR(200) NOT NULL,
        WARD NVARCHAR(100) NULL,
        DISTRICT NVARCHAR(100) NULL,
        CITY NVARCHAR(100) NOT NULL,
        LONGITUDE DECIMAL(10,7) NULL,
        LATITUDE DECIMAL(10,7) NULL,
        USER_ID INT NOT NULL,
        CONSTRAINT PK_ACCOMMODATION PRIMARY KEY (ACCOMMODATION_ID),
        CONSTRAINT FK_ACCOMMODATION_HOST FOREIGN KEY (USER_ID) REFERENCES dbo.HOST(USER_ID),
        CONSTRAINT CK_ACCOMMODATION_STAR CHECK (STAR_RATING BETWEEN 1 AND 5),
        CONSTRAINT CK_ACCOMMODATION_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180),
        CONSTRAINT CK_ACCOMMODATION_LATITUDE CHECK (LATITUDE BETWEEN -90 AND 90)
    );

    -- 12. Một khách chỉ được lưu mỗi cơ sở một lần vào danh sách yêu thích.
    CREATE TABLE dbo.WISHLIST (
        WISHLIST_ID INT IDENTITY(1,1) NOT NULL,
        SAVED_DATE DATETIME2(0) NOT NULL CONSTRAINT DF_WISHLIST_DATE DEFAULT (SYSDATETIME()),
        USER_ID INT NOT NULL,
        ACCOMMODATION_ID INT NOT NULL,
        CONSTRAINT PK_WISHLIST PRIMARY KEY (WISHLIST_ID),
        CONSTRAINT UQ_WISHLIST_GUEST_ACCOM UNIQUE (USER_ID, ACCOMMODATION_ID),
        CONSTRAINT FK_WISHLIST_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID),
        CONSTRAINT FK_WISHLIST_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID)
    );

    -- 13-17. Các loại cơ sở lưu trú và tiện nghi chung của khách sạn.
    CREATE TABLE dbo.HOTEL (
        ACCOMMODATION_ID INT NOT NULL,
        NUMBER_OF_FLOORS SMALLINT NOT NULL,
        CONSTRAINT PK_HOTEL PRIMARY KEY (ACCOMMODATION_ID),
        CONSTRAINT FK_HOTEL_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_HOTEL_FLOORS CHECK (NUMBER_OF_FLOORS > 0)
    );

    CREATE TABLE dbo.HOTEL_FACILITIES (
        ACCOMMODATION_ID INT NOT NULL,
        COMMON_FACILITIES NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_HOTEL_FACILITIES PRIMARY KEY (ACCOMMODATION_ID, COMMON_FACILITIES),
        CONSTRAINT FK_HOTEL_FACILITIES_HOTEL FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.HOTEL(ACCOMMODATION_ID)
    );

    CREATE TABLE dbo.RESORT (
        ACCOMMODATION_ID INT NOT NULL,
        PROPERTY_AREA DECIMAL(12,2) NOT NULL,
        CONSTRAINT PK_RESORT PRIMARY KEY (ACCOMMODATION_ID),
        CONSTRAINT FK_RESORT_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_RESORT_AREA CHECK (PROPERTY_AREA > 0)
    );

    CREATE TABLE dbo.APARTMENT (
        ACCOMMODATION_ID INT NOT NULL,
        NUMBER_OF_BEDROOMS SMALLINT NOT NULL,
        CONSTRAINT PK_APARTMENT PRIMARY KEY (ACCOMMODATION_ID),
        CONSTRAINT FK_APARTMENT_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_APARTMENT_BEDROOMS CHECK (NUMBER_OF_BEDROOMS > 0)
    );

    CREATE TABLE dbo.HOMESTAY (
        ACCOMMODATION_ID INT NOT NULL,
        HOUSE_TYPE NVARCHAR(100) NOT NULL,
        NUMBER_OF_RENTAL_ROOMS SMALLINT NOT NULL,
        CONSTRAINT PK_HOMESTAY PRIMARY KEY (ACCOMMODATION_ID),
        CONSTRAINT FK_HOMESTAY_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_HOMESTAY_ROOMS CHECK (NUMBER_OF_RENTAL_ROOMS > 0)
    );

    -- 18-19. Danh mục tiện ích và các tiện ích của từng cơ sở.
    CREATE TABLE dbo.AMENITY (
        AMENITY_NAME NVARCHAR(100) NOT NULL,
        AMENITY_GROUP NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_AMENITY PRIMARY KEY (AMENITY_NAME)
    );

    CREATE TABLE dbo.ACCOMMODATION_AMENITY (
        ACCOMMODATION_ID INT NOT NULL,
        AMENITY_NAME NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_ACCOMMODATION_AMENITY PRIMARY KEY (ACCOMMODATION_ID, AMENITY_NAME),
        CONSTRAINT FK_ACCOM_AMENITY_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT FK_ACCOM_AMENITY_AMENITY FOREIGN KEY (AMENITY_NAME) REFERENCES dbo.AMENITY(AMENITY_NAME)
    );

    -- 20. Tên hạng phòng chỉ duy nhất trong cùng một cơ sở.
    CREATE TABLE dbo.ROOM_TYPE (
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        AREA DECIMAL(10,2) NOT NULL,
        NUMBER_OF_BEDS SMALLINT NOT NULL,
        BED_TYPE NVARCHAR(100) NOT NULL,
        ADULTS SMALLINT NOT NULL,
        CHILDREN SMALLINT NOT NULL CONSTRAINT DF_ROOM_TYPE_CHILDREN DEFAULT (0),
        [VIEW] NVARCHAR(100) NULL,
        CONSTRAINT PK_ROOM_TYPE PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME),
        CONSTRAINT FK_ROOM_TYPE_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_ROOM_TYPE_AREA CHECK (AREA > 0),
        CONSTRAINT CK_ROOM_TYPE_BEDS CHECK (NUMBER_OF_BEDS > 0),
        CONSTRAINT CK_ROOM_TYPE_ADULTS CHECK (ADULTS >= 1),
        CONSTRAINT CK_ROOM_TYPE_CHILDREN CHECK (CHILDREN >= 0)
    );

    -- 21. Tiện nghi của hạng phòng, tham chiếu bằng cặp mã cơ sở và tên hạng phòng.
    CREATE TABLE dbo.ROOM_TYPE_AMENITIES (
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        IN_ROOM_AMENITIES NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_ROOM_TYPE_AMENITIES PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, IN_ROOM_AMENITIES),
        CONSTRAINT FK_ROOM_TYPE_AMENITIES_TYPE FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME)
            REFERENCES dbo.ROOM_TYPE(ACCOMMODATION_ID, ROOM_NAME)
    );

    -- 22. Phòng thực tế. Các phòng trong cùng cơ sở không được trùng số phòng.
    CREATE TABLE dbo.ROOM (
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        ROOM_NUMBER VARCHAR(20) NOT NULL,
        AVAILABILITY_STATUS VARCHAR(15) NOT NULL CONSTRAINT DF_ROOM_STATUS DEFAULT ('AVAILABLE'),
        CONSTRAINT PK_ROOM PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, ROOM_NUMBER),
        CONSTRAINT UQ_ROOM_ACCOM_NUMBER UNIQUE (ACCOMMODATION_ID, ROOM_NUMBER),
        CONSTRAINT FK_ROOM_TYPE FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME)
            REFERENCES dbo.ROOM_TYPE(ACCOMMODATION_ID, ROOM_NAME),
        CONSTRAINT CK_ROOM_STATUS CHECK (AVAILABILITY_STATUS IN ('AVAILABLE','BOOKED','MAINTENANCE'))
    );

    -- 23. Bảng giá riêng cho từng hạng phòng.
    CREATE TABLE dbo.ROOM_RATE (
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        ROOM_RATE_ID INT NOT NULL,
        UNIT_PRICE DECIMAL(18,2) NOT NULL,
        FREE_CANCELLATION BIT NOT NULL CONSTRAINT DF_RATE_FREE_CANCEL DEFAULT (0),
        EFFECTIVE_DATE DATE NOT NULL,
        CHILD_PRICE DECIMAL(18,2) NOT NULL CONSTRAINT DF_RATE_CHILD_PRICE DEFAULT (0),
        BREAKFAST_INCLUDED BIT NOT NULL CONSTRAINT DF_RATE_BREAKFAST DEFAULT (0),
        CONSTRAINT PK_ROOM_RATE PRIMARY KEY (ACCOMMODATION_ID, ROOM_NAME, ROOM_RATE_ID),
        CONSTRAINT FK_ROOM_RATE_TYPE FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME)
            REFERENCES dbo.ROOM_TYPE(ACCOMMODATION_ID, ROOM_NAME),
        CONSTRAINT CK_ROOM_RATE_ID CHECK (ROOM_RATE_ID > 0),
        CONSTRAINT CK_ROOM_RATE_PRICE CHECK (UNIT_PRICE > 0),
        CONSTRAINT CK_ROOM_RATE_CHILD_PRICE CHECK (CHILD_PRICE >= 0)
    );

    -- 24-26. Ảnh cơ sở và ảnh hạng phòng dùng PHOTO_ID làm khóa chính theo BTL1.
    CREATE TABLE dbo.PHOTO (
        PHOTO_ID INT IDENTITY(1,1) NOT NULL,
        URL NVARCHAR(2048) NOT NULL,
        [DESCRIPTION] NVARCHAR(500) NULL,
        UPLOAD_DATE DATETIME2(0) NOT NULL CONSTRAINT DF_PHOTO_DATE DEFAULT (SYSDATETIME()),
        CONSTRAINT PK_PHOTO PRIMARY KEY (PHOTO_ID)
    );

    CREATE TABLE dbo.ACCOMMODATION_PHOTO (
        PHOTO_ID INT NOT NULL,
        ACCOMMODATION_ID INT NOT NULL,
        CONSTRAINT PK_ACCOMMODATION_PHOTO PRIMARY KEY (PHOTO_ID),
        CONSTRAINT FK_ACCOM_PHOTO_PHOTO FOREIGN KEY (PHOTO_ID) REFERENCES dbo.PHOTO(PHOTO_ID),
        CONSTRAINT FK_ACCOM_PHOTO_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID)
    );

    CREATE TABLE dbo.ROOM_TYPE_PHOTO (
        PHOTO_ID INT NOT NULL,
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        CONSTRAINT PK_ROOM_TYPE_PHOTO PRIMARY KEY (PHOTO_ID),
        CONSTRAINT FK_ROOM_TYPE_PHOTO_PHOTO FOREIGN KEY (PHOTO_ID) REFERENCES dbo.PHOTO(PHOTO_ID),
        CONSTRAINT FK_ROOM_TYPE_PHOTO_TYPE FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME)
            REFERENCES dbo.ROOM_TYPE(ACCOMMODATION_ID, ROOM_NAME)
    );

    -- 27. Đơn đặt phòng. Kiểm tra ngày lưu trú, số khách và 4 trạng thái theo BTL1.
    CREATE TABLE dbo.BOOKING (
        BOOKING_ID INT IDENTITY(1,1) NOT NULL,
        [STATUS] VARCHAR(12) NOT NULL CONSTRAINT DF_BOOKING_STATUS DEFAULT ('PENDING'),
        ADULTS SMALLINT NOT NULL,
        CHILDREN SMALLINT NOT NULL CONSTRAINT DF_BOOKING_CHILDREN DEFAULT (0),
        BOOKING_CODE VARCHAR(30) NOT NULL,
        PIN_CODE VARCHAR(10) NOT NULL,
        BOOKING_DATE DATE NOT NULL CONSTRAINT DF_BOOKING_DATE DEFAULT (CONVERT(DATE,SYSDATETIME())),
        CHECK_IN_DATE DATE NOT NULL,
        CHECK_OUT_DATE DATE NOT NULL,
        ESTIMATED_ARRIVAL_TIME TIME(0) NULL,
        SPECIAL_REQUESTS NVARCHAR(1000) NULL,
        USER_ID INT NOT NULL,
        ACCOMMODATION_ID INT NOT NULL,
        CONSTRAINT PK_BOOKING PRIMARY KEY (BOOKING_ID),
        CONSTRAINT UQ_BOOKING_CODE UNIQUE (BOOKING_CODE),
        -- Thêm UNIQUE để bảng chi tiết tham chiếu cả mã đơn và mã cơ sở.
        CONSTRAINT UQ_BOOKING_ACCOM UNIQUE (BOOKING_ID, ACCOMMODATION_ID),
        CONSTRAINT FK_BOOKING_GUEST FOREIGN KEY (USER_ID) REFERENCES dbo.GUEST(USER_ID),
        CONSTRAINT FK_BOOKING_ACCOM FOREIGN KEY (ACCOMMODATION_ID) REFERENCES dbo.ACCOMMODATION(ACCOMMODATION_ID),
        CONSTRAINT CK_BOOKING_STATUS CHECK ([STATUS] IN ('PENDING','CONFIRMED','COMPLETED','CANCELLED')),
        CONSTRAINT CK_BOOKING_DATES CHECK (CHECK_OUT_DATE > CHECK_IN_DATE),
        CONSTRAINT CK_BOOKING_BOOKED_BEFORE_STAY CHECK (BOOKING_DATE <= CHECK_IN_DATE),
        CONSTRAINT CK_BOOKING_ADULTS CHECK (ADULTS >= 1),
        CONSTRAINT CK_BOOKING_CHILDREN CHECK (CHILDREN >= 0),
        CONSTRAINT CK_BOOKING_CODE_NOT_EMPTY CHECK (LEN(LTRIM(RTRIM(BOOKING_CODE))) > 0),
        CONSTRAINT CK_BOOKING_PIN_NOT_EMPTY CHECK (LEN(LTRIM(RTRIM(PIN_CODE))) > 0)
    );

    -- 28. Hạng phòng trong chi tiết phải thuộc đúng cơ sở của đơn đặt.
    CREATE TABLE dbo.BOOKING_ROOM_TYPE (
        BOOKING_ID INT NOT NULL,
        ACCOMMODATION_ID INT NOT NULL,
        ROOM_NAME NVARCHAR(100) NOT NULL,
        ROOM_PRICE_AT_BOOKING DECIMAL(18,2) NOT NULL,
        RESERVED_QUANTITY SMALLINT NOT NULL,
        CONSTRAINT PK_BOOKING_ROOM_TYPE PRIMARY KEY (BOOKING_ID, ACCOMMODATION_ID, ROOM_NAME),
        CONSTRAINT FK_BOOKING_ROOM_TYPE_BOOKING FOREIGN KEY (BOOKING_ID, ACCOMMODATION_ID)
            REFERENCES dbo.BOOKING(BOOKING_ID, ACCOMMODATION_ID),
        CONSTRAINT FK_BOOKING_ROOM_TYPE_TYPE FOREIGN KEY (ACCOMMODATION_ID, ROOM_NAME)
            REFERENCES dbo.ROOM_TYPE(ACCOMMODATION_ID, ROOM_NAME),
        CONSTRAINT CK_BOOKING_ROOM_TYPE_PRICE CHECK (ROOM_PRICE_AT_BOOKING > 0),
        CONSTRAINT CK_BOOKING_ROOM_TYPE_QUANTITY CHECK (RESERVED_QUANTITY > 0)
    );

    -- 29. Mỗi đơn áp dụng tối đa một voucher, giữ khóa chính ghép như BTL1.
    CREATE TABLE dbo.BOOKING_VOUCHER (
        BOOKING_ID INT NOT NULL,
        VOUCHER_CODE VARCHAR(50) NOT NULL,
        CONSTRAINT PK_BOOKING_VOUCHER PRIMARY KEY (BOOKING_ID, VOUCHER_CODE),
        CONSTRAINT UQ_BOOKING_VOUCHER_BOOKING UNIQUE (BOOKING_ID),
        CONSTRAINT FK_BOOKING_VOUCHER_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES dbo.BOOKING(BOOKING_ID),
        CONSTRAINT FK_BOOKING_VOUCHER_VOUCHER FOREIGN KEY (VOUCHER_CODE) REFERENCES dbo.VOUCHER(VOUCHER_CODE)
    );

    -- 30. Mỗi đơn có tối đa một bản ghi thanh toán theo quan hệ 1:1 trong EERD.
    CREATE TABLE dbo.PAYMENT (
        PAYMENT_ID INT IDENTITY(1,1) NOT NULL,
        TRANSACTION_CODE VARCHAR(100) NULL,
        CURRENCY CHAR(3) NOT NULL CONSTRAINT DF_PAYMENT_CURRENCY DEFAULT ('VND'),
        PAYMENT_DATE DATETIME2(0) NULL,
        PAYMENT_METHOD VARCHAR(15) NOT NULL,
        AMOUNT DECIMAL(18,2) NOT NULL,
        PAYMENT_STATUS VARCHAR(10) NOT NULL CONSTRAINT DF_PAYMENT_STATUS DEFAULT ('PENDING'),
        BOOKING_ID INT NOT NULL,
        CARD_NUMBER VARCHAR(19) NULL,
        CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID),
        CONSTRAINT UQ_PAYMENT_BOOKING UNIQUE (BOOKING_ID),
        CONSTRAINT FK_PAYMENT_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES dbo.BOOKING(BOOKING_ID),
        CONSTRAINT FK_PAYMENT_CARD FOREIGN KEY (CARD_NUMBER) REFERENCES dbo.PAYMENT_CARD(CARD_NUMBER),
        CONSTRAINT CK_PAYMENT_AMOUNT CHECK (AMOUNT >= 0),
        CONSTRAINT CK_PAYMENT_STATUS CHECK (PAYMENT_STATUS IN ('PENDING','PAID','FAILED','REFUNDED')),
        CONSTRAINT CK_PAYMENT_METHOD CHECK (PAYMENT_METHOD IN ('CARD','AT_PROPERTY')),
        CONSTRAINT CK_PAYMENT_METHOD_CARD CHECK (
            (PAYMENT_METHOD = 'CARD' AND CARD_NUMBER IS NOT NULL) OR
            (PAYMENT_METHOD = 'AT_PROPERTY' AND CARD_NUMBER IS NULL)
        )
    );
    -- Mã giao dịch có thể chưa có; khi có thì không được trùng.
    CREATE UNIQUE INDEX UX_PAYMENT_TRANSACTION_CODE
        ON dbo.PAYMENT(TRANSACTION_CODE) WHERE TRANSACTION_CODE IS NOT NULL;

    -- 31. Thông tin hủy đơn, mỗi đơn có tối đa một bản ghi.
    CREATE TABLE dbo.CANCELLATION (
        BOOKING_ID INT NOT NULL,
